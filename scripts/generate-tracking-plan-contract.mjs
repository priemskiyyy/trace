import { writeFileSync } from "node:fs";

const EVENT_COUNT = 500;
const TYPED_FROM = 167;
const SCHEMA_FROM = 334;

const getName = (index) => `Event ${String(index).padStart(3, "0")}`;

const getDefinition = (index) => {
  if (index < TYPED_FROM) {
    return "event()";
  }

  if (index < SCHEMA_FROM) {
    return `event<{ index: ${index}; label: string }>()`;
  }

  return `event(schema<{ index: ${index}; answer: "yes" | "no" }>())`;
};

const declarations = Array.from(
  { length: EVENT_COUNT },
  (_, index) => `  "${getName(index)}": ${getDefinition(index)},`,
).join("\n");

const source = `// Generated by scripts/generate-tracking-plan-contract.mjs. Do not edit it by hand: change the script and run \`node scripts/generate-tracking-plan-contract.mjs\`.
import { expectTypeOf } from "vitest";

import { createMockAdapter } from "src/mock/createMockAdapter";
import type { Receipt } from "src/types/Receipt";
import type { StandardSchema } from "src/types/StandardSchema";
import type { TrackOptions } from "src/types/TrackOptions";
import { event } from "src/utils/event";
import { Trace } from "src/utils/Trace";

declare const schema: <TOutput extends object>() => StandardSchema<
  TOutput,
  TOutput
>;

export const trackingPlan = {
${declarations}
};

export const trace = new Trace({
  events: trackingPlan,
  destinations: {
    product: createMockAdapter().adapter,
    backend: createMockAdapter({ name: "backend" }).adapter,
  },
});

export const first = trace.track("${getName(0)}");
export const middle = trace.track("${getName(250)}", { index: 250, label: "a" });

export const last = trace.track(
  "${getName(EVENT_COUNT - 1)}",
  { index: ${EVENT_COUNT - 1}, answer: "no" },
  { to: ["backend"] },
);

expectTypeOf(trace.track<"${getName(0)}">).parameters.toEqualTypeOf<
  [
    name: "${getName(0)}",
    properties?: undefined,
    options?: TrackOptions<"product" | "backend">,
  ]
>();
expectTypeOf(trace.track<"${getName(250)}">).parameters.toEqualTypeOf<
  [
    name: "${getName(250)}",
    properties: { index: 250; label: string },
    options?: TrackOptions<"product" | "backend">,
  ]
>();
expectTypeOf(trace.track<"${getName(EVENT_COUNT - 1)}">).parameters.toEqualTypeOf<
  [
    name: "${getName(EVENT_COUNT - 1)}",
    properties: { index: ${EVENT_COUNT - 1}; answer: "yes" | "no" },
    options?: TrackOptions<"product" | "backend">,
  ]
>();
expectTypeOf(last).toEqualTypeOf<Receipt<"product" | "backend">>();

// @ts-expect-error The plan has ${EVENT_COUNT} events, and "${getName(EVENT_COUNT)}" is not one of them.
trace.track("${getName(EVENT_COUNT)}");

// @ts-expect-error "maybe" is not an answer this event's schema declares.
trace.track("${getName(EVENT_COUNT - 1)}", { index: ${EVENT_COUNT - 1}, answer: "maybe" });

// @ts-expect-error A label is a string.
trace.track("${getName(250)}", { index: 250, label: 3 });

// @ts-expect-error This event requires its properties, however large the plan.
trace.track("${getName(250)}");

// @ts-expect-error This event takes no properties.
trace.track("${getName(0)}", { index: 0 });
`;

writeFileSync(
  new URL(
    "../packages/core/src/utils/trackingPlan.contracts.ts",
    import.meta.url,
  ),
  source,
);
